"""Write the full PostgreSQL DDL for every Docs Health table to docs/schema_postgresql.sql.

    python -m scripts.export_schema

Use it to review the schema or to create the tables by hand (e.g. in pgAdmin / psql)
in an existing database such as scribe_docs. `python -m scripts.check_db --create`
does the same automatically once DATABASE_URL points at that database.
"""
from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from app import models  # noqa: F401
from app.db import Base

OUT = Path(__file__).resolve().parents[2] / "docs" / "schema_postgresql.sql"


def main() -> None:
    dialect = postgresql.dialect()
    parts = ["-- Docs Health schema for PostgreSQL (generated by scripts/export_schema.py)",
             "-- Safe to run in an empty schema. Tables are created in dependency order.", ""]
    deferred_fks = []
    for table in Base.metadata.sorted_tables:
        ddl = str(CreateTable(table).compile(dialect=dialect)).strip()
        parts.append(ddl.replace("CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ", 1) + ";\n")
        for index in sorted(table.indexes, key=lambda i: i.name or ""):
            parts.append(str(CreateIndex(index, if_not_exists=True).compile(dialect=dialect)).strip() + ";")
        parts.append("")
        deferred_fks += [fk for fk in table.foreign_key_constraints if fk.use_alter]
    if deferred_fks:
        parts.append("-- Circular references, added after all tables exist")
        for fk in deferred_fks:
            cols = ", ".join(c.name for c in fk.columns)
            ref = fk.elements[0].column.table.name
            refcols = ", ".join(e.column.name for e in fk.elements)
            parts.append(f'ALTER TABLE {fk.table.name} ADD CONSTRAINT {fk.name} FOREIGN KEY ({cols}) '
                         f'REFERENCES {ref} ({refcols}) ON DELETE {fk.ondelete or "NO ACTION"};')
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({len(Base.metadata.sorted_tables)} tables)")


if __name__ == "__main__":
    main()
